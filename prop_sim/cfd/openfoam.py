@dataclass
class AirfoilCaseConfig:
    """2 次元翼型ケースの設定."""

    reynolds: float = 1.2e4
    alpha_deg: float = 0.0
    u_inf: float = 1.0          # コード長 1 m, U=1 m/s とすれば nu = 1/Re
    n_surface: int = 160
    n_radial: int = 90
    far_field_radius: float = 20.0
    radial_grading: float = 3000.0
    span: float = 0.1
    solver: str = "simpleFoam"
    end_time: float = 3000.0     # simpleFoam では反復回数
    write_interval: float = 1000.0
    delta_t: float = 1.0
    residual_tol: float = 1.0e-6
    n_procs: int = 1
    average_last_fraction: float = 0.25   # 非定常のとき後半何割を平均するか
    #: ``forceCoeffs`` functionObject を使うか. 既定は使わず, 書き出された
    #: 場から :mod:`prop_sim.cfd.foam_io` で積分する (モジュール docstring 参照).
    use_function_objects: bool = False
    #: ``"ogrid"`` = 自前の O 型格子 (既定), ``"blockmesh"`` = blockMesh.
    #: 薄くキャンバの大きい断面では blockMesh 版は破綻する
    #: (:mod:`prop_sim.cfd.mesh` の docstring 参照).
    mesh: str = "ogrid"
    normal_length: float = 0.5     # 壁法線押し出しを効かせる距離 (コード基準)
    smooth_passes: int = 120       # 周方向平滑化の回数
    max_courant: float = 3.0       # 非定常ソルバの Courant 数上限
    keep_all_times: bool = False   # 全時刻を残す (時刻歴を見たいとき)
    restart: bool = False          # 既存の最終時刻から続きを解く


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


@dataclass
class OpenFoamCase:
    """OpenFOAM ケースディレクトリの生成と実行."""

    directory: Path
    section: SectionShape
    config: AirfoilCaseConfig = field(default_factory=AirfoilCaseConfig)

    def __post_init__(self) -> None:
        self.directory = Path(self.directory)

    # ------------------------------------------------------------- 生成
    def write(self) -> Path:
        """ケース一式を書き出す (OpenFOAM が無くても実行できる)."""
        c = self.config
        d = self.directory
        if d.exists() and not c.restart:
            shutil.rmtree(d)
        a = np.deg2rad(c.alpha_deg)
        u = (c.u_inf * np.cos(a), c.u_inf * np.sin(a), 0.0)
        nu = c.u_inf * 1.0 / c.reynolds          # コード長 = 1 m

        pts = surface_points(self.section, c.n_surface)
        if c.mesh == "ogrid":
            d.mkdir(parents=True, exist_ok=True)
            write_polymesh(d / "constant/polyMesh", ogrid_nodes(
                pts, n_radial=c.n_radial, far_field_radius=c.far_field_radius,
                radial_grading=c.radial_grading, normal_length=c.normal_length,
                smooth_passes=c.smooth_passes), span=c.span)
        elif c.mesh == "blockmesh":
            _write(d / "system/blockMeshDict", build_blockmesh_dict(
                pts, far_field_radius=c.far_field_radius, n_radial=c.n_radial,
                radial_grading=c.radial_grading, span=c.span))
        else:
            raise ValueError(f"未知の mesh: {c.mesh!r}")
        _write(d / "system/controlDict", self._control_dict(u))
        _write(d / "system/fvSchemes", _FV_SCHEMES[c.solver])
        _write(d / "system/fvSolution", _FV_SOLUTION[c.solver])
        _write(d / "system/decomposeParDict", _decompose(c.n_procs))
        _write(d / "constant/transportProperties",
               _head("dictionary", "transportProperties", "constant")
               + f"\ntransportModel  Newtonian;\n\nnu              {nu:.8g};\n")
        _write(d / "constant/turbulenceProperties",
               _head("dictionary", "turbulenceProperties", "constant")
               + "\nsimulationType  laminar;\n")
        _write(d / "0/U", _field_u(u))
        _write(d / "0/p", _field_p())
        return d

    def _control_dict(self, u) -> str:
        c = self.config
        a = np.deg2rad(c.alpha_deg)
        mag = float(np.hypot(u[0], u[1]))
        if not c.use_function_objects:
            unsteady = c.solver != "simpleFoam"
            # 非定常なら Courant 数で刻みを自動調整し, 書き出しは実時間基準.
            # 定常 (simpleFoam) では endTime = 反復回数.
            extra = (
                f"adjustTimeStep  yes;\nmaxCo           {c.max_courant:g};\n"
                f"maxDeltaT       {c.write_interval:g};\n"
                if unsteady else ""
            )
            n_keep = max(int(round(1.0 / max(c.average_last_fraction, 1e-9))), 2)
            return (
                _head("dictionary", "controlDict", "system")
                + f"""
application     {c.solver};
startFrom       {"latestTime" if c.restart else "startTime"};
startTime       0;
stopAt          endTime;
endTime         {c.end_time:g};
deltaT          {c.delta_t:g};
writeControl    {"adjustableRunTime" if unsteady else "timeStep"};
writeInterval   {c.write_interval:g};
purgeWrite      {0 if c.keep_all_times else n_keep};
writeFormat     ascii;
writePrecision  8;
timeFormat      general;
timePrecision   8;
runTimeModifiable false;
{extra}
functions
{{
}}
"""
            )
        return (
            _head("dictionary", "controlDict", "system")
            + f"""
application     {c.solver};
startFrom       startTime;
startTime       0;
stopAt          endTime;
endTime         {c.end_time:g};
deltaT          {c.delta_t:g};
writeControl    timeStep;
writeInterval   {c.write_interval:g};
purgeWrite      2;
writeFormat     ascii;
writePrecision  8;
runTimeModifiable true;

functions
{{
    forceCoeffs
    {{
        type            forceCoeffs;
        libs            ("libforces.so");
        writeControl    timeStep;
        writeInterval   1;
        log             no;
        patches         (airfoil);
        rho             rhoInf;
        rhoInf          1;
        CofR            (0.25 0 0);
        liftDir         ({-np.sin(a):.10g} {np.cos(a):.10g} 0);
        dragDir         ({np.cos(a):.10g} {np.sin(a):.10g} 0);
        pitchAxis       (0 0 1);
        magUInf         {mag:.10g};
        lRef            1;
        Aref            {c.span:.10g};
    }}
    residuals
    {{
        type            solverInfo;
        libs            ("libutilityFunctionObjects.so");
        fields          (U p);
        writeResidualFields no;
    }}
}}
"""
        )

    # ------------------------------------------------------------- 実行
    def run(self, bashrc: str | None = None, timeout: float = 3600.0) -> dict:
        """blockMesh -> ソルバ を実行する."""
        bashrc = find_openfoam() if bashrc is None else bashrc
        if bashrc is None:
            raise RuntimeError(
                "OpenFOAM が見つかりません "
                "(PROP_SIM_OPENFOAM_BASHRC 環境変数で etc/bashrc を指定できます)"
            )
        src = f"source {bashrc} >/dev/null 2>&1; " if bashrc else ""
        log = {}
        steps = (("blockMesh",) if self.config.mesh == "blockmesh" else ()) + (
            self.config.solver,)
        for cmd in steps:
            # 進捗が見えるようログへ直接リダイレクトする (長い計算になるため)
            logfile = self.directory / f"log.{cmd}"
            r = subprocess.run(
                ["bash", "-c", f"set -a; {src}set +a; cd {self.directory} && "
                               f"{cmd} > {logfile.name} 2>&1"],
                capture_output=True, text=True, timeout=timeout,
            )
            log[cmd] = r.returncode
            if r.returncode != 0:
                tail = logfile.read_text()[-1500:] if logfile.is_file() else r.stderr
                raise RuntimeError(f"{cmd} が失敗しました (log.{cmd} 参照)\n{tail}")
        return log

    # ------------------------------------------------------------- 結果
    def coefficients(self) -> dict[str, float]:
        """``Cl`` / ``Cd`` / ``CmPitch`` を返す.

        ``use_function_objects`` が偽 (既定) のときは書き出された場を
        :func:`~prop_sim.cfd.foam_io.patch_wrench` で積分する. 複数の
        時刻が残っていれば後半 ``average_last_fraction`` を平均し,
        そのばらつきを ``*_std`` として返す (非定常性の指標).
        """
        if self.config.use_function_objects:
            return read_force_coefficients(
                self.directory, self.config.average_last_fraction)
        return integrate_coefficients(
            self.directory, self.config, patch="airfoil")


def _written_times(case_dir) -> list[str]:
    out = []
    for p in Path(case_dir).iterdir():
        if not p.is_dir() or not (p / "U").is_file():
            continue
        try:
            out.append((float(p.name), p.name))
        except ValueError:
            pass
    return [n for _, n in sorted(out)]


def integrate_coefficients(
    case_dir, config: AirfoilCaseConfig | None = None, *, patch: str = "airfoil"
) -> dict[str, float]:
    """壁面荷重を積分して空力係数にする (functionObject 不要).

    ``controlDict`` の ``purgeWrite`` が ``1 / average_last_fraction`` 回分
    だけ残すようにしてあるので, 初期値 (``0``) 以外の残っている時刻を
    すべて平均する. 定常計算なら 1 個しか残らず, そのまま最終解になる.

    ``CmPitch`` は 1/4 コードまわり・**頭上げが正** (``Airfoil.cm`` と同じ).
    """
    case_dir = Path(case_dir)
    c = config or AirfoilCaseConfig()
    times = _written_times(case_dir)
    if not times:
        raise FileNotFoundError(f"{case_dir} に書き出された場がありません")
    if len(times) > 1:
        times = [t for t in times if float(t) > 0.0] or times[-1:]

    a = np.deg2rad(c.alpha_deg)
    drag_dir = np.array([np.cos(a), np.sin(a), 0.0])
    lift_dir = np.array([-np.sin(a), np.cos(a), 0.0])
    q = 0.5 * c.u_inf**2 * c.span          # rho = 1, lRef = Aref/span = 1
    # 幾何モーメント Mz = sum (r x F)_z は, x が下流・y が上向きのとき
    # **頭下げ**が正になる (前縁は -x 側にあるため). 空力の慣用
    # (頭上げが正, `Airfoil.cm` と同じ) に合わせて符号を反転する.
    cm_sign = -1.0

    mesh = None
    cl, cd, cm, fp, fv = [], [], [], [], []
    for t in times:
        w = patch_wrench(case_dir, patch, time=t, rho=1.0, mesh=mesh)
        mesh = w["mesh"]
        cl.append(float(w["force"] @ lift_dir) / q)
        cd.append(float(w["force"] @ drag_dir) / q)
        cm.append(cm_sign * float(w["moment"][2]) / q)
        fp.append(float(w["force_pressure"] @ drag_dir) / q)
        fv.append(float(w["force_viscous"] @ drag_dir) / q)
    out = {
        "Cl": float(np.mean(cl)), "Cd": float(np.mean(cd)),
        "CmPitch": float(np.mean(cm)),
        "Cl_std": float(np.std(cl)), "Cd_std": float(np.std(cd)),
        "CmPitch_std": float(np.std(cm)),
        "Cd_pressure": float(np.mean(fp)), "Cd_viscous": float(np.mean(fv)),
        "n_samples": float(len(times)), "t_end": float(times[-1]),
    }
    return out


def read_force_coefficients(
    case_dir, average_last_fraction: float = 0.25
) -> dict[str, float]:
    """``postProcessing/forceCoeffs/*/coefficient*.dat`` を読む.

    後半 ``average_last_fraction`` を時間平均し, その区間の標準偏差
    (``cl_std`` 等) も返す — 非定常かどうかの判定に使える.
    """
    case_dir = Path(case_dir)
    files = sorted((case_dir / "postProcessing" / "forceCoeffs").glob("*/coeff*.dat"))
    if not files:
        raise FileNotFoundError(f"{case_dir} に forceCoeffs の出力がありません")
    header, rows = [], []
    for f in files:
        for line in f.read_text().splitlines():
            if line.startswith("#"):
                if "Time" in line:
                    header = line.lstrip("#").split()
                continue
            rows.append([float(v) for v in line.split()])
    if not rows:
        raise ValueError("forceCoeffs の出力が空です")
    data = np.asarray(rows)
    order = np.argsort(data[:, 0])
    data = data[order]
    n = max(int(data.shape[0] * average_last_fraction), 1)
    tail = data[-n:]
    out = {"n_samples": float(data.shape[0]), "t_end": float(data[-1, 0])}
    for k, name in enumerate(header):
        if k == 0:
            continue
        key = name.replace("(", "").replace(")", "")
        out[key] = float(tail[:, k].mean())
        out[key + "_std"] = float(tail[:, k].std())
    return out


# ---------------------------------------------------------------- ポーラ
def run_polar(
    section: SectionShape,
    alphas_deg,
    reynolds: float = 1.2e4,
    *,
    workdir="cfd_runs",
    config: AirfoilCaseConfig | None = None,
    bashrc: str | None = None,
    timeout: float = 3600.0,
    progress: bool = True,
    keep_cases: bool = False,
) -> dict:
    """迎角を振って cl, cd を求め, :class:`TabulatedAirfoil` を作る.

    Returns
    -------
    dict
        ``alpha_deg``, ``cl``, ``cd``, ``cm``, ``cl_std``, ``cd_std``,
        ``airfoil`` (:class:`TabulatedAirfoil`), ``cases``.
    """
    workdir = Path(workdir)
    workdir.mkdir(parents=True, exist_ok=True)
    alphas = np.atleast_1d(np.asarray(alphas_deg, dtype=float))
    base = config or AirfoilCaseConfig()
    cl, cd, cm, cls_, cds, cases = [], [], [], [], [], []
    for a in alphas:
        cfg = AirfoilCaseConfig(**{**base.__dict__, "alpha_deg": float(a),
                                   "reynolds": float(reynolds)})
        cdir = workdir / f"a{a:+06.2f}_Re{reynolds:.0f}".replace("+", "p").replace(
            "-", "m")
        case = OpenFoamCase(cdir, section, cfg)
        case.write()
        if progress:  # pragma: no cover
            print(f"  CFD alpha={a:+.2f} deg, Re={reynolds:.0f} ...", flush=True)
        case.run(bashrc=bashrc, timeout=timeout)
        c = case.coefficients()
        cl.append(c.get("Cl", np.nan))
        cd.append(c.get("Cd", np.nan))
        cm.append(c.get("CmPitch", c.get("Cm", np.nan)))
        cls_.append(c.get("Cl_std", np.nan))
        cds.append(c.get("Cd_std", np.nan))
        cases.append(cdir)
        if not keep_cases:
            for sub in cdir.glob("[0-9]*"):
                if sub.is_dir() and sub.name != "0":
                    shutil.rmtree(sub, ignore_errors=True)
    cl, cd, cm = map(np.asarray, (cl, cd, cm))
    return {
        "alpha_deg": alphas, "cl": cl, "cd": cd, "cm": cm,
        "cl_std": np.asarray(cls_), "cd_std": np.asarray(cds),
        "reynolds": reynolds, "cases": cases,
        "airfoil": TabulatedAirfoil(
            alpha_deg=alphas, cl=cl, cd=cd, cm=cm,
            name=f"{section.name} CFD Re={reynolds:.0f}",
            reynolds_ref=reynolds, aspect_ratio=3.0),
    }


