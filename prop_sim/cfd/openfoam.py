"""OpenFOAM を使った 2 次元翼型 CFD.

なぜ 2 次元翼型なのか
---------------------
本パッケージで残っている最大の不確かさは **Re = 2,000 - 20,000 の翼型
ポーラ** であって, 3 次元の渦構造ではない (Lv3 の渦法が BEMT と 0.6 % で
一致することで確認済み). したがって費用対効果がいちばん高い CFD は
**断面まわりの 2 次元計算**である.

    翼断面 (SectionShape)  --CFD-->  cl(alpha, Re), cd(alpha, Re)
                                        |
                                        v
                                  TabulatedAirfoil  --> BEMT / 渦法

これで :func:`~prop_sim.section.airfoil_from_section` の経験補正
(``camber_efficiency`` / ``bubble_penalty`` / ``reynolds_lift_slope``) を
物理計算に置き換えられる.

格子
----
断面まわりの **O 型格子**を blockMesh で生成する. 断面を N 点で離散化し,
各周方向区間ごとに 1 ブロック (半径方向 n_r セル) を置く. 後縁に厚みが
ある断面 (射出成型のマイクロプロペラは 1-3 %c ある) では O 型格子が
そのまま使えて素直.

解法
----
Re が 10^4 前後なので層流. 定常 ``simpleFoam`` で解き, 残差が落ちない
(剥離による非定常) 場合は ``pimpleFoam`` に切り替えて時間平均をとる.

制限
----
* **3 次元ロータ CFD はここでは回さない**. 滑りメッシュ RANS は
  数百万セル・数時間〜数日で, 本パッケージの想定外.
  外部で回した結果は :meth:`SurrogateModel.from_conditions` で取り込める.
* Re < 10^4 の層流剥離泡は 2 次元計算でも難しい. 2 次元では剥離せん断層の
  3 次元不安定が表現できず, 剥離泡が実際より大きく出る傾向がある.
  結果は「経験式より根拠がある推定」であって真値ではない.
"""

