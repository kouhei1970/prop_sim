def _head(cls: str, obj: str, location: str | None = None) -> str:
    extra = f'location    "{location}";\n    ' if location else ""
    return _HEADER.format(cls=cls, obj=obj, extra=extra)


def find_openfoam() -> str | None:
    """OpenFOAM の ``etc/bashrc`` を探す. 見つからなければ None."""
    env = os.environ.get("PROP_SIM_OPENFOAM_BASHRC")
    if env and Path(env).is_file():
        return env
    for c in _ENV_CANDIDATES:
        if Path(c).is_file():
            return c
    if shutil.which("blockMesh") and shutil.which("simpleFoam"):
        return ""          # すでに PATH が通っている
    return None


# --------------------------------------------------------------------- 形状
def surface_points(
    section: SectionShape, n: int = 160, te_gap_min: float = 1.0e-4
) -> np.ndarray:
    """断面の閉曲線を反時計回りに ``n`` 点で離散化する.

    後縁上面 -> 前縁 -> 後縁下面 の順に並べ, 後縁に厚みがあればそのまま
    base 面として閉じる (重複点は作らない).
    """
    s = section.resample(max(n // 2 + 1, 8))
    up = np.stack([s.x, s.upper], axis=1)
    lo = np.stack([s.x, s.lower], axis=1)
    if abs(up[-1, 1] - lo[-1, 1]) < te_gap_min:      # 鋭い後縁 -> 1 点に統合
        pts = np.vstack([up[::-1], lo[1:-1]])
    else:
        pts = np.vstack([up[::-1], lo[1:]])
    if abs(pts[0, 1] - pts[-1, 1]) < te_gap_min and abs(pts[0, 0] - pts[-1, 0]) < 1e-12:
        pts = pts[:-1]
    # 反時計回りに揃える (blockMesh のブロックが inside-out にならないように)
    area = 0.5 * np.sum(pts[:, 0] * np.roll(pts[:, 1], -1)
                        - np.roll(pts[:, 0], -1) * pts[:, 1])
    if area < 0.0:
        pts = pts[::-1]
    return pts


def polygon_centroid(points: np.ndarray) -> np.ndarray:
    """閉多角形の図心. 面積が潰れている場合は頂点の平均に落とす."""
    p = np.asarray(points, float)
    q = np.roll(p, -1, axis=0)
    cross = p[:, 0] * q[:, 1] - q[:, 0] * p[:, 1]
    a = 0.5 * cross.sum()
    if abs(a) < 1e-12:
        return p.mean(axis=0)
    return ((p + q) * cross[:, None]).sum(axis=0) / (6.0 * a)


def build_blockmesh_dict(
    points: np.ndarray,
    *,
    far_field_radius: float = 20.0,
    n_radial: int = 90,
    radial_grading: float = 3000.0,
    span: float = 0.1,
    centre=None,
) -> str:
    """O 型格子の ``blockMeshDict`` を生成する.

    Parameters
    ----------
    points:
        断面の閉曲線 ``(N, 2)`` (コード長 1 に正規化, 反時計回り).
    far_field_radius:
        遠方境界の半径 (コード長基準).
    n_radial, radial_grading:
        半径方向のセル数と, 最外セル / 最内セル の比.
    span:
        2 次元計算の z 方向の厚み.
    centre:
        遠方円の中心. ``None`` なら断面の図心を使う. キャンバの大きい
        薄翼では 1/4 コード点 ``(0.25, 0)`` が断面の**外**に出てしまい
        O 型格子が破綻するため, 図心を既定にしてある.
    """
    p = np.asarray(points, dtype=float)
    n = p.shape[0]
    centre = polygon_centroid(p) if centre is None else np.asarray(centre, float)

    # 遠方境界の点は中心からの偏角で割り付ける (放射線が断面にほぼ直交する).
    # ただし断面が中心について星形でないと偏角が逆行してブロックが裏返るので,
    # 最小刻み ``dmin`` を課して単調化し, 合計がちょうど 2 pi になるよう
    # 正規化する. 中心が断面の内部にあれば, この補正はほとんど効かない.
    ang = np.unwrap(np.arctan2(p[:, 1] - centre[1], p[:, 0] - centre[0]))
    d = np.diff(np.concatenate([ang, [ang[0] + 2.0 * np.pi]]))
    d = np.maximum(d, 0.2 * 2.0 * np.pi / n)
    d *= 2.0 * np.pi / d.sum()
    ang = ang[0] + np.concatenate([[0.0], np.cumsum(d)[:-1]])
    outer = centre + far_field_radius * np.stack([np.cos(ang), np.sin(ang)], axis=1)

    # 右手系になっているか (局所 x = 半径方向, 局所 y = 周方向)
    radial = outer - p
    circ = np.roll(outer, -1, axis=0) - outer
    twist = radial[:, 0] * circ[:, 1] - radial[:, 1] * circ[:, 0]
    if np.any(twist <= 0.0):
        bad = int(np.argmin(twist))
        raise ValueError(
            f"O 型格子のブロック {bad} が裏返ります "
            f"(断面が中心 {tuple(centre)} について星形でない可能性). "
            "surface_points の点数を増やすか centre を変えてください"
        )
    # 放射線が断面に対して寝すぎていないか (blockMesh の面法線チェック対策)
    tang = np.roll(p, -1, axis=0) - p
    ok = np.linalg.norm(tang, axis=1) > 0
    cosang = np.abs(np.einsum("ij,ij->i", radial[ok], tang[ok])) / (
        np.linalg.norm(radial[ok], axis=1) * np.linalg.norm(tang[ok], axis=1))
    if cosang.max() > 0.999:
        raise ValueError(
            "放射線が断面表面とほぼ平行になっています "
            f"(cos = {cosang.max():.4f}, ブロック {int(np.argmax(cosang))})"
        )

    verts = []
    for z in (0.0, span):
        for arr in (p, outer):
            verts.extend(f"    ({x:.10g} {y:.10g} {z:.10g})" for x, y in arr)
    # 添字: s(z0)=i, o(z0)=n+i, s(z1)=2n+i, o(z1)=3n+i
    #
    # ブロックの局所座標は (x, y, z) = (半径外向き, 周方向, スパン方向).
    # 断面を反時計回りに並べてあるので 周方向 t と外向き r は t x r = -z,
    # つまり (周, 半径, スパン) の順だと左手系になり blockMesh が
    # "is inside-out" で落ちる. r x t = +z なので半径方向を局所 x に取る.
    blocks, airfoil, farfield, back, front = [], [], [], [], []
    for i in range(n):
        j = (i + 1) % n
        v = (i, n + i, n + j, j, 2 * n + i, 3 * n + i, 3 * n + j, 2 * n + j)
        blocks.append(
            f"    hex ({' '.join(map(str, v))}) ({n_radial} 1 1) "
            f"simpleGrading ({radial_grading:g} 1 1)"
        )
        # blockMesh の面規約: x-min (0 4 7 3), x-max (1 2 6 5),
        #                     z-min (0 3 2 1), z-max (4 5 6 7)
        airfoil.append(f"        ({v[0]} {v[4]} {v[7]} {v[3]})")
        farfield.append(f"        ({v[1]} {v[2]} {v[6]} {v[5]})")
        back.append(f"        ({v[0]} {v[3]} {v[2]} {v[1]})")
        front.append(f"        ({v[4]} {v[5]} {v[6]} {v[7]})")

    return (
        _head("dictionary", "blockMeshDict", "system")
        + "\nscale   1;\n\nvertices\n(\n"
        + "\n".join(verts)
        + "\n);\n\nblocks\n(\n"
        + "\n".join(blocks)
        + "\n);\n\nedges\n(\n);\n\nboundary\n(\n"
        + "    airfoil\n    {\n        type wall;\n        faces\n        (\n"
        + "\n".join(airfoil)
        + "\n        );\n    }\n"
        + "    farfield\n    {\n        type patch;\n        faces\n        (\n"
        + "\n".join(farfield)
        + "\n        );\n    }\n"
        + "    frontAndBack\n    {\n        type empty;\n        faces\n        (\n"
        + "\n".join(back + front)
        + "\n        );\n    }\n);\n\nmergePatchPairs\n(\n);\n"
    )


